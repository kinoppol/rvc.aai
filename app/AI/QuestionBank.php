     * เลือกชุดคำถามให้เหมาะกับรหัสวิชาและชื่อบทเรียนที่ครูเลือก
     *
     * @param list<string> $lessonTitles
     * @return list<array{type:string,question:string,choices:list<string>,answer:int,explanation:string}>
     */
    public static function pick(string $courseCode, array $lessonTitles): array
    {
        $key = self::subjectKey($courseCode, $lessonTitles);
        $pool = self::POOL[$key] ?? self::POOL['general'];

        return $pool;
    }

    private static function subjectKey(string $courseCode, array $lessonTitles): string
    {
        $text = $courseCode . ' ' . implode(' ', $lessonTitles);

        return match (true) {
            str_contains($text, 'นิวแมติกส์'), str_contains($text, 'ไฮดรอลิกส์'), str_contains($courseCode, '20127-2005') => 'pneumatics',
            str_contains($text, 'เมคคาทรอนิกส์'), str_contains($text, 'เซนเซอร์'), str_contains($courseCode, '20127-2002') => 'mechatronics',
            str_contains($text, 'ไมโครคอนโทรลเลอร์'), str_contains($courseCode, '30128') => 'micro',
            str_contains($text, 'ไฟฟ้า'), str_contains($text, 'วงจร'), str_contains($courseCode, '20100-1005') => 'electrical',
            default => 'general',
        };
    }

