               7. บันทึกหลังการสอน — ให้เว้นไว้ว่า (ครูกรอกหลังจัดการเรียนการสอนจริง)
            4. ขึ้นบรรทัดใหม่ภายใน body ให้ใช้ \\n ห้ามขึ้นบรรทัดจริง เพราะหนึ่งบรรทัดต้องเป็น JSON หนึ่งชุด
            5. ปิดท้ายด้วยบรรทัด {"done":true}
            TXT;
    }
