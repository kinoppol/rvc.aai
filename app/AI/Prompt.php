<?php

declare(strict_types=1);

namespace App\AI;

/**
 * แปลง userPrompt ที่ระบบส่งให้ผู้ให้บริการ (เป็น JSON spec) ให้เป็นคำสั่งภาษาไทยสำหรับโมเดลจริง
 *
 * SimulatedProvider อ่าน spec เป็น JSON ตรง ๆ ส่วนโมเดลจริงต้องได้คำสั่งที่บอกรูปแบบผลลัพธ์
 * ให้ชัด เพราะ QuizGenerator / LessonPlanGenerator แปลงผลลัพธ์เป็น NDJSON ทีละบรรทัด
 */
final class Prompt
{
    /** ป้ายชื่อชนิดข้อสอบที่ใช้สื่อสารกับโมเดล */
    private const TYPE_LABELS = [
        'choice' => 'ปรนัย 4 ตัวเลือก',
        'short_answer' => 'อัตนัยตอบสั้น',
        'matching' => 'จับคู่',
    ];

    public static function userText(string $userPrompt): string
    {
        $spec = json_decode($userPrompt, true);
        if (!is_array($spec)) {
            return $userPrompt;
        }

        $text = match ($spec['task'] ?? '') {
            'chat' => (string) ($spec['message'] ?? ''),
            'quiz' => self::quiz($spec),
            'lesson_plan' => self::lessonPlan($spec),
            'unit_outline' => self::unitOutline($spec),
            'assignment' => self::assignment($spec),
            'unit_content' => self::unitContent($spec),
            'course_outcomes' => self::courseOutcomes($spec),
            'behavior_analysis' => self::behaviorAnalysis($spec),
            'model_roles' => self::modelRoles($spec),
            default => $userPrompt,
        };

        // ปิดโหมดคิดของโมเดลตระกูล qwen3 (สวิตช์ /no_think ท้ายข้อความ) — ดูเหตุผลที่ Drafter::objects()
        return empty($spec['no_think']) ? $text : $text . "\n\n/no_think";
    }

    /**
     * จัดบทบาทให้โมเดลของผู้ให้บริการรายหนึ่ง — แต่ละโมเดลเหมาะกับงานสอนด้านไหน
     *
     * @param array<string,mixed> $spec
     */
    private static function modelRoles(array $spec): string
    {
        $models = implode("\n", array_map(static fn ($m): string => '- ' . $m, (array) ($spec['models'] ?? [])));
        $roles = implode("\n", array_map(
            static fn (string $k, array $v): string => "- {$k} = {$v[0]}",
            array_keys(ModelRoles::ROLES),
            ModelRoles::ROLES
        ));
        $provider = trim((string) ($spec['provider'] ?? '')) ?: 'ไม่ระบุ';

        return <<<TXT
            ช่วยจัดบทบาทให้โมเดล AI ต่อไปนี้ (ผู้ให้บริการ: {$provider}) สำหรับใช้ในระบบจัดการเรียนการสอนของวิทยาลัยเทคนิค ครูใช้ภาษาไทย

            โมเดล:
            {$models}

            บทบาทที่เลือกได้ (ใส่ได้หลายบทบาท):
            {$roles}

            หลักการพิจารณาจากชื่อและความรู้ของคุณเกี่ยวกับโมเดล:
            - โมเดล OCR เฉพาะทาง (อ่านภาพเป็นข้อความอย่างเดียว) → roles เป็น ["ocr"]
            - โมเดลข้อความที่รับภาพได้ด้วย (multimodal/vision เช่น Gemini, GPT-4o, Qwen-VL) → ใส่ "ocr" เพิ่มจากบทบาทงานข้อความ
            - โมเดลที่ไม่ใช่โมเดลข้อความและอ่านภาพไม่ได้ เช่น TTS/เสียง, embedding, rerank, สร้างภาพ, guard → roles เป็น [] (ไม่ใช้กับงานสอน)
            - โมเดลใหญ่หรือแบบคิดก่อนตอบ (reasoning, pro, 70B ขึ้นไป) เหมาะกับ plan และ quiz ที่ต้องการความถูกต้องและงานยาว
            - โมเดลเล็ก/เร็ว (flash, mini, lite, ขนาดไม่เกิน 14B) เหมาะกับ chat และ content
            - โมเดลที่ภาษาไทยอ่อนไม่ควรได้ plan
            - โมเดลข้อความทั่วไปควรได้อย่างน้อยหนึ่งบทบาท

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งโมเดลต่อหนึ่งบรรทัด ครบทุกโมเดล ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. แต่ละบรรทัดใช้รูปแบบ {"model":"ชื่อโมเดลตรงตามรายการ","roles":["chat","content"],"note":"เหมาะกับงานอะไร ภาษาไทยไม่เกิน 1 ประโยค"}
            3. บรรทัดสุดท้ายคือ {"done":true}
            TXT;
    }

    /**
     * ร่างเนื้อหาของหน่วยการเรียนหนึ่งหน่วย แยกเป็นหัวข้อย่อยพร้อมคำอธิบาย
     *
     * @param array<string,mixed> $spec
     */
    private static function unitContent(array $spec): string
    {
        // count = 0 คือให้ผู้ช่วยเลือกจำนวนหัวข้อเองตามความกว้างของเนื้อหา
        $count = (int) ($spec['count'] ?? 0);
        $count = $count === 0 ? 0 : max(2, min(10, $count));
        $split = $count === 0
            ? 'แบ่งเป็นหัวข้อย่อยตามความเหมาะสมของเนื้อหา (2–10 หัวข้อ) เลือกจำนวนเองจากความกว้างของสาระสำคัญและจุดประสงค์ ไม่ต้องแตกหัวข้อเกินจำเป็น'
            : "แบ่งเป็น {$count} หัวข้อย่อย";
        $finish = $count === 0 ? 'ครบทุกหัวข้อ' : "ครบ {$count} หัวข้อ";
        $keyContent = trim((string) ($spec['key_content'] ?? '')) ?: '(ไม่ได้ระบุ ให้อนุมานจากชื่อหน่วย)';
        $objectives = trim((string) ($spec['objectives'] ?? '')) ?: '(ไม่ได้ระบุ)';
        $existing = (array) ($spec['existing'] ?? []);
        $existingText = $existing === []
            ? 'ยังไม่มีหัวข้อย่อยเดิมในหน่วยนี้'
            : "ห้ามซ้ำกับหัวข้อที่มีอยู่แล้ว:\n- " . implode("\n- ", $existing);
        $note = trim((string) ($spec['note'] ?? ''));
        $noteText = $note === '' ? '' : "\n\nสิ่งที่ครูสั่งเพิ่ม: {$note}";

        return <<<TXT
            เขียนเนื้อหาสำหรับสอนในหน่วยการเรียน "{$spec['unit']}" ของรายวิชา {$spec['course_code']} {$spec['course_name']}
            {$split}

            สาระสำคัญของหน่วย:
            {$keyContent}

            จุดประสงค์การเรียนรู้:
            {$objectives}

            {$existingText}{$noteText}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งหัวข้อต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. แต่ละบรรทัดใช้รูปแบบนี้
            {"no":1,"title":"ชื่อหัวข้อย่อย","content":"เนื้อหาที่ใช้สอนได้จริง อธิบายให้ครบ ยกตัวอย่างจากงานอาชีพจริงประกอบ"}
            3. เนื้อหาแต่ละหัวข้อยาวอย่างน้อย 5 ประโยค เขียนเป็นย่อหน้าอ่านรู้เรื่อง ขึ้นบรรทัดใหม่ด้วย \\n ได้
            4. เรียงจากพื้นฐานไปสู่การประยุกต์ใช้ และให้ครอบคลุมจุดประสงค์การเรียนรู้ข้างต้น
            5. เมื่อ{$finish} ให้ปิดท้ายด้วยบรรทัด {"done":true}
            TXT;
    }

    /**
     * ร่างใบงานของหน่วยการเรียนหนึ่งหน่วย
     *
     * @param array<string,mixed> $spec
     */
    private static function assignment(array $spec): string
    {
        $unit = (string) ($spec['unit'] ?? '');
        $keyContent = trim((string) ($spec['key_content'] ?? '')) ?: '(ไม่ได้ระบุ ให้อนุมานจากชื่อหน่วย)';
        $score = (float) ($spec['max_score'] ?? 10);
        $note = trim((string) ($spec['note'] ?? ''));
        $noteText = $note === '' ? '' : "\n\nสิ่งที่ครูสั่งเพิ่ม: {$note}";

        return <<<TXT
            ออกแบบใบงานภาษาไทยสำหรับรายวิชา {$spec['course_code']} {$spec['course_name']}

            หน่วยการเรียน: {$unit}
            สาระสำคัญของหน่วย:
            {$keyContent}

            คะแนนเต็มของใบงาน: {$score} คะแนน{$noteText}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น JSON อ็อบเจกต์เดียว ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. ใช้รูปแบบนี้
            {"title":"ชื่อใบงาน","objective":"จุดประสงค์ของใบงาน 1-2 ประโยค","steps":["ขั้นตอนที่ต้องทำ ข้อละหนึ่งรายการ"],"deliverable":"สิ่งที่ต้องส่ง","criteria":[{"item":"เกณฑ์การให้คะแนน","score":5}]}
            3. ให้ steps มี 3-6 ข้อ สั่งงานเป็นรูปธรรม ทำได้จริงในบริบทงานอาชีพ ไม่ใช่คำถามท่องจำ
            4. คะแนนใน criteria ทุกข้อรวมกันต้องเท่ากับ {$score} พอดี
            TXT;
    }

    /**
     * ออกแบบรายชื่อหน่วยการเรียนของทั้งรายวิชาให้ครอบคลุมคำอธิบายรายวิชา
     *
     * @param array<string,mixed> $spec
     */
    private static function unitOutline(array $spec): string
    {
        $count = max(1, min(20, (int) ($spec['count'] ?? 8)));
        $description = trim((string) ($spec['description'] ?? '')) ?: '(ไม่ได้ระบุ ให้อนุมานจากชื่อวิชา)';
        $existing = (array) ($spec['existing'] ?? []);
        // ระบุให้ชัดว่า "หน่วยใหม่เพิ่มอีก N หน่วย ไม่นับของเดิม" — คำสั่งเดิมกำกวม โมเดลแบบคิดก่อนตอบ
        // วนคิดว่าจำนวนรวมหรือจำนวนเพิ่มจนหมดเวลาโดยไม่ตอบ JSON สักบรรทัด
        $existingText = $existing === []
            ? 'รายวิชานี้ยังไม่มีหน่วยการเรียน'
            : sprintf("รายวิชานี้มีหน่วยการเรียนอยู่แล้ว %d หน่วย (ห้ามซ้ำ ไม่ต้องร่างใหม่ และไม่นับรวมในจำนวนที่ขอ):
- ", count($existing))
                . implode("
- ", $existing);
        $what = $existing === []
            ? "ออกแบบรายชื่อหน่วยการเรียนของรายวิชา {$spec['course_code']} {$spec['course_name']} จำนวน {$count} หน่วย"
            : "ออกแบบหน่วยการเรียนใหม่ของรายวิชา {$spec['course_code']} {$spec['course_name']} เพิ่มอีก {$count} หน่วย (นับเฉพาะหน่วยใหม่ ไม่รวมหน่วยที่มีอยู่แล้ว)";
        $note = trim((string) ($spec['note'] ?? ''));
        $noteText = $note === '' ? '' : "

สิ่งที่ครูสั่งเพิ่ม:
{$note}";
        $scheduleText = self::outlineSchedule((array) ($spec['schedule'] ?? []));

        return <<<TXT
            {$what}

            คำอธิบายรายวิชา:
            {$description}

            {$existingText}{$scheduleText}{$noteText}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งหน่วยต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON เริ่มตอบด้วย JSON บรรทัดแรกได้ทันที
            2. แต่ละบรรทัดใช้รูปแบบนี้
            {"no":1,"title":"ชื่อหน่วยการเรียน","key_content":"สาระสำคัญ 2-3 ประโยค","objectives":"1. จุดประสงค์ข้อแรก\\n2. จุดประสงค์ข้อสอง","competencies":"1. สมรรถนะข้อแรก\\n2. สมรรถนะข้อสอง","hours":6}
            3. objectives และ competencies เป็นข้อความเดียว (string) ขึ้นบรรทัดใหม่ด้วย \\n ไม่ใช่ array
            4. เรียงหน่วยจากพื้นฐานไปสู่การประยุกต์ใช้ และให้ทุกหน่วยรวมกันครอบคลุมคำอธิบายรายวิชาข้างต้นครบถ้วน
            5. ใช้ภาษาไทยและบริบทงานอาชีพจริง ไม่ตั้งชื่อหน่วยกว้างลอย ๆ
            6. ต้องครบ {$count} หน่วยพอดี แล้วปิดท้ายด้วยบรรทัด {"done":true,"total":{$count}}
            TXT;
    }

    /**
     * สรุปผลลัพธ์การเรียนรู้ระดับรายวิชา (Course Learning Outcomes) จากข้อมูลรายวิชาที่ครูกรอก
     *
     * @param array<string,mixed> $spec
     */
    private static function courseOutcomes(array $spec): string
    {
        $count = max(2, min(8, (int) ($spec['count'] ?? 4)));
        $or = static fn (string $k): string => trim((string) ($spec[$k] ?? '')) ?: '(ไม่ได้ระบุ)';

        return <<<TXT
            สรุปผลลัพธ์การเรียนรู้ระดับรายวิชา {$count} ข้อ ของรายวิชา {$spec['course_code']} {$spec['course_name']}
            ตามแนวแผนการจัดการเรียนรู้มุ่งเน้นสมรรถนะ หลักสูตร สอศ. พ.ศ. 2567

            คำอธิบายรายวิชา:
            {$or('description')}

            จุดประสงค์รายวิชา:
            {$or('objectives')}

            สมรรถนะรายวิชา:
            {$or('competencies')}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งข้อต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. แต่ละบรรทัดใช้รูปแบบนี้ {"outcome":"ผลลัพธ์การเรียนรู้หนึ่งข้อ"}
            3. แต่ละข้อขึ้นต้นด้วยคำกริยาที่วัดได้ (เช่น อธิบาย ปฏิบัติ ติดตั้ง วิเคราะห์ ออกแบบ แก้ปัญหา) ระบุสิ่งที่ผู้เรียนทำได้เมื่อจบรายวิชา และเงื่อนไข/เกณฑ์ตามบริบทงานอาชีพจริง
            4. กระชับ ข้อละหนึ่งประโยค ยาวไม่เกินประมาณ 30 คำ ไม่ยกตัวอย่างยาว ๆ ในวงเล็บหรือหลังคำว่า "เช่น"
            5. ครอบคลุมทั้งด้านความรู้ ทักษะ และคุณลักษณะที่พึงประสงค์ ไม่ลอกจุดประสงค์หรือสมรรถนะมาตรง ๆ ไม่ใส่เลขข้อ
            6. ต้องครบ {$count} ข้อ แล้วปิดท้ายด้วยบรรทัด {"done":true,"total":{$count}}
            TXT;
    }

    /**
     * ตารางวิเคราะห์พฤติกรรมการเรียนรู้ (แบบที่ 2 หลักสูตร 2567): ระดับ K/S/A/Ap และร้อยละประเมินผลของแต่ละหน่วย
     *
     * @param array<string,mixed> $spec
     */
    private static function behaviorAnalysis(array $spec): string
    {
        $or = static fn (string $k): string => trim((string) ($spec[$k] ?? '')) ?: '(ไม่ได้ระบุ)';
        $units = [];
        foreach ((array) ($spec['units'] ?? []) as $u) {
            $units[] = "หน่วยที่ {$u['no']} {$u['title']}" . (!empty($u['hours']) ? " ({$u['hours']} ชั่วโมง)" : '')
                . "\n  สาระสำคัญ: " . (trim((string) $u['key_content']) ?: '-')
                . "\n  จุดประสงค์: " . (trim((string) $u['objectives']) ?: '-')
                . "\n  สมรรถนะ: " . (trim((string) $u['competencies']) ?: '-')
                . (!empty($u['topics']) ? "\n  หัวข้อเนื้อหา: " . $u['topics'] : '')
                . (!empty($u['worksheets']) ? "\n  ใบงาน: " . $u['worksheets'] : '');
        }
        $count = count($units);
        $unitText = implode("\n\n", $units);

        return <<<TXT
            วิเคราะห์พฤติกรรมการเรียนรู้ (ตารางวิเคราะห์พฤติกรรมการเรียนรู้ แบบที่ 2 แผนการจัดการเรียนรู้หลักสูตร สอศ. 2567)
            ของรายวิชา {$spec['course_code']} {$spec['course_name']} ทฤษฎี {$spec['theory']} ปฏิบัติ {$spec['practice']} ชั่วโมง/สัปดาห์

            คำอธิบายรายวิชา:
            {$or('description')}

            จุดประสงค์รายวิชา:
            {$or('objectives')}

            สมรรถนะรายวิชา:
            {$or('competencies')}

            ผลลัพธ์การเรียนรู้ระดับรายวิชา:
            {$or('outcomes')}

            หน่วยการเรียนรู้ทั้งหมด {$count} หน่วย:
            {$unitText}

            ระดับความสามารถที่คาดหวัง:
            - พุทธิพิสัย K1 ความรู้ความจำ K2 ความเข้าใจ K3 การนำไปใช้ K4 การวิเคราะห์ K5 การประเมินค่า K6 การสร้างสรรค์ (ใส่ได้หลายระดับ)
            - ทักษะพิสัย S1 เลียนแบบ S2 ทำได้ตามแบบ S3 ทำได้ถูกต้อง S4 ทำได้อย่างต่อเนื่อง S5 ทำได้อย่างเป็นธรรมชาติ (ระดับเดียว)
            - จิตพิสัย A1 รับรู้ A2 ตอบสนอง A3 การสร้างคุณค่า A4 จัดระบบคุณค่านิยม A5 การสร้างลักษณะนิสัย (ระดับเดียว)
            - ประยุกต์ใช้และรับผิดชอบ Ap1 ปฏิบัติงานตามแบบแผน Ap2 ตามแบบแผนและปรับตัวในการเปลี่ยนแปลงไม่ซับซ้อน Ap3 วางแผนงานที่ได้รับมอบหมายและแก้ปัญหาบางเรื่อง Ap4 วางแผนงานที่รับผิดชอบและแก้ปัญหาที่ซับซ้อน Ap5 ประยุกต์ความรู้ทักษะวางแผนแก้ปัญหาและพัฒนานวัตกรรม (ระดับเดียว)

            หลักการ:
            - ระดับต้องสอดคล้องกับคำกริยาในจุดประสงค์/สมรรถนะของหน่วย และไม่ต่ำกว่าจุดประสงค์รายวิชา
            - หน่วยต้น ๆ มักเป็นพื้นฐาน (K1–K3, S1–S3) หน่วยท้าย ๆ ที่เป็นงานบูรณาการระดับสูงขึ้นได้ ระดับ ปวช. โดยทั่วไป Ap ไม่เกิน Ap3 ปวส. ไม่เกิน Ap4
            - weight = ร้อยละประเมินผลของหน่วย ตามความยาก ปริมาณเนื้อหา และชั่วโมง ส่วน outcome_weight = ร้อยละของการประเมินผลลัพธ์การเรียนรู้ระดับรายวิชา (มักอยู่ระหว่าง 10–30)
            - weight ทุกหน่วยรวมกับ outcome_weight ต้องเท่ากับ 100 พอดี

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งหน่วยต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. แต่ละบรรทัดใช้รูปแบบนี้ {"unit":1,"k":["K1","K2"],"s":"S2","a":"A2","ap":"Ap1","weight":10}
            3. ต้องครบ {$count} หน่วย ตามลำดับเลขหน่วย แล้วตามด้วยบรรทัด {"outcome_weight":20}
            4. ปิดท้ายด้วยบรรทัด {"done":true}
            TXT;
    }

    /**
     * ตารางสัปดาห์ที่ระบบวางไว้ให้หน่วยใหม่ (จาก UnitOutlineController) — ให้ขนาดเนื้อหาพอดีกับเวลา
     * และแบ่งเนื้อหาเป็นครึ่งก่อน/หลังสอบกลางภาค
     *
     * @param array<string,mixed> $s
     */
    private static function outlineSchedule(array $s): string
    {
        if (empty($s['units'])) {
            return '';
        }

        $lines = [sprintf(
            "\n\nตารางเวลา: ภาคเรียนนี้เรียน %d สัปดาห์รวมวัดผล สัปดาห์ละ %d ชั่วโมง (ทฤษฎี + ปฏิบัติ) · ระบบแบ่งเวลาให้หน่วยใหม่แล้ว ให้ขนาดเนื้อหาแต่ละหน่วยพอดีกับเวลานี้",
            (int) $s['weeks'],
            (int) $s['weekly']
        )];
        foreach ((array) $s['units'] as $u) {
            $range = $u['from'] === $u['to'] ? "สัปดาห์ที่ {$u['from']}" : "สัปดาห์ที่ {$u['from']}–{$u['to']}";
            $lines[] = "- หน่วยที่ {$u['no']}: {$u['weeks']} สัปดาห์ ({$range}, {$u['hours']} ชั่วโมง)";
        }
        if (!empty($s['midterm_week'])) {
            $lines[] = "- สอบกลางภาคสัปดาห์ที่ {$s['midterm_week']} หลังหน่วยที่ {$s['midterm_after']} — หน่วยที่ 1–{$s['midterm_after']} ต้องครอบคลุมเนื้อหาครึ่งแรกของวิชาครบในตัว ส่วนหน่วยหลังจากนั้นเป็นครึ่งหลัง";
        }
        if (!empty($s['final_week'])) {
            $lines[] = "- สอบปลายภาคสัปดาห์ที่ {$s['final_week']} (ไม่ต้องร่างหน่วยสอบ ระบบสร้างให้เอง)";
        }

        return implode("\n", $lines);
    }

    /** @param array<string,mixed> $spec */
    private static function quiz(array $spec): string
    {
        $count = max(1, min(30, (int) ($spec['count'] ?? 5)));
        $types = array_map(
            static fn (string $t): string => self::TYPE_LABELS[$t] ?? $t,
            (array) ($spec['types'] ?? ['choice'])
        );
        $lessons = implode("\n- ", (array) ($spec['lesson_titles'] ?? []));
        $typeList = implode(' และ ', $types) ?: 'ปรนัย 4 ตัวเลือก';
        $source = trim((string) ($spec['source'] ?? ''));
        // มีเนื้อหาจริงของหน่วย: ให้ออกจากเนื้อหานี้เท่านั้น เพื่อไม่ให้ถามเกินสิ่งที่สอน
        $sourceText = $source === '' ? '' : <<<TXT


            ===== เนื้อหาที่ครูสอนจริง (ฐานความรู้สำหรับออกข้อสอบ) =====
            {$source}
            ===== จบเนื้อหา =====

            กติกาสำคัญ: ทุกข้อต้องตอบได้จากเนื้อหาข้างต้นเท่านั้น ห้ามถามเรื่องที่ไม่มีในเนื้อหา
            เฉลยและคำอธิบายต้องสอดคล้องกับเนื้อหา กระจายข้อให้ครอบคลุมทุกหัวข้อ ไม่กระจุกอยู่หัวข้อเดียว
            TXT;
        $avoid = trim((string) ($spec['avoid'] ?? ''));
        // ข้อที่ออกไปแล้ว (รอบก่อน ๆ หรือข้อที่ครูกดร่างใหม่) — ห้ามถามซ้ำหรือถามประเด็นเดิม
        $avoidText = $avoid === '' ? '' : "\n\nข้อที่ออกไปแล้ว ห้ามซ้ำหรือถามประเด็นเดิม:\n" . (str_starts_with($avoid, '- ') ? $avoid : '- ' . $avoid);
        // ข้อที่รอบนี้ออกไปแล้วแต่ยังไม่ครบ (QuizGenerator ขอเพิ่มเมื่อโมเดลส่งข้อที่ใช้ไม่ได้มา)
        $existing = array_values(array_filter(array_map('strval', (array) ($spec['existing'] ?? []))));
        if ($existing !== []) {
            $avoidText .= "\n\nข้อที่ออกไปแล้วในชุดนี้ (ห้ามซ้ำ ให้ออกข้อใหม่อีก {$count} ข้อโดยไม่นับข้อเหล่านี้):\n- " . implode("\n- ", array_slice($existing, 0, 40));
        }

        $raw = (array) ($spec['types'] ?? ['choice']);
        $onlyChoice = $raw === [] || $raw === ['choice'];
        $hasChoice = $onlyChoice || in_array('choice', $raw, true);
        $typeRule = $onlyChoice
            ? "ข้อสอบทั้ง {$count} ข้อต้องเป็นปรนัย 4 ตัวเลือก (\"type\":\"choice\") เท่านั้น ห้ามมีข้ออัตนัย ข้อเติมคำ หรือข้อที่ให้เขียนตอบแม้แต่ข้อเดียว"
            : "ออกเฉพาะชนิดที่กำหนด ({$typeList}) เท่านั้น ห้ามออกชนิดอื่น";
        $choiceRules = $hasChoice ? <<<TXT

            หลักการเขียนข้อปรนัย — ต้องทำตามทุกข้อ:
            - โจทย์ถามประเด็นเดียวชัดเจน อ่านแล้วรู้ว่าถามอะไรโดยไม่ต้องดูตัวเลือก หลีกเลี่ยงโจทย์ปฏิเสธ ถ้าจำเป็นให้เน้นคำว่า "ไม่"
            - มีคำตอบที่ถูกที่สุดเพียงข้อเดียว ตัวลวงทั้ง 3 ข้อต้องผิดจริงแต่ดูสมเหตุสมผลสำหรับผู้ที่ยังไม่เข้าใจ
            - ตัวเลือกทั้ง 4 ยาวใกล้เคียงกันและเป็นเรื่องเดียวกัน ห้ามให้คำตอบที่ถูกยาวหรือละเอียดกว่าตัวเลือกอื่นจนเดาได้
            - ห้ามใช้ตัวเลือก "ถูกทุกข้อ" "ผิดทุกข้อ" "ไม่มีข้อใดถูก" หรือ "ข้อ ก และ ข" และห้ามมีคำในโจทย์ที่ชี้คำตอบ
            - กระจายตำแหน่งคำตอบที่ถูกให้ทั่วทั้ง ก ข ค ง ในจำนวนใกล้เคียงกัน และห้ามให้คำตอบที่ถูกอยู่ตำแหน่งเดียวกันติดต่อกันเกิน 2 ข้อ
            - "explanation" อธิบายว่าทำไมคำตอบนั้นถูก
            TXT : '';
        $shortRule = in_array('short_answer', $raw, true)
            ? 'ข้ออัตนัยใช้ "type":"short_answer" ให้ "choices" เป็น [] และ "score" เป็น 2'
            : 'ทุกข้อต้องมี "type":"choice" และมี "choices" 4 ตัวเลือกที่ "is_correct":true เพียงหนึ่งตัว';

        return <<<TXT
            ออกข้อสอบภาษาไทยจำนวน {$count} ข้อ สำหรับรายวิชา {$spec['course_code']} {$spec['course_name']}

            บทเรียนที่ต้องออกข้อสอบ:
            - {$lessons}{$sourceText}{$avoidText}

            ชนิดข้อสอบที่ต้องการ: {$typeList}
            ระดับความยาก: {$spec['level']}
            {$typeRule}{$choiceRules}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งข้อสอบต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. แต่ละบรรทัดใช้รูปแบบนี้ (ข้อปรนัยต้องมี 4 ตัวเลือก และถูกต้องเพียงข้อเดียว):
            {"no":1,"type":"choice","question":"โจทย์","explanation":"เหตุผลของคำตอบที่ถูก","score":1,"choices":[{"label":"ก","content":"ตัวเลือก","is_correct":false},{"label":"ข","content":"ตัวเลือก","is_correct":true},{"label":"ค","content":"ตัวเลือก","is_correct":false},{"label":"ง","content":"ตัวเลือก","is_correct":false}]}
            3. {$shortRule}
            4. เขียนโจทย์ให้ตรงกับเนื้อหาบทเรียนข้างต้นและบริบทงานอาชีพจริง ไม่ถามกว้างเกินไป ไม่ถามเกินเนื้อหาที่ให้มา
            5. เมื่อครบ {$count} ข้อ ให้ปิดท้ายด้วยบรรทัด {"done":true,"total":{$count}}
            TXT;
    }

    /** @param array<string,mixed> $spec */
    private static function lessonPlan(array $spec): string
    {
        $unit = (string) ($spec['unit'] ?? '');
        $hours = (string) ($spec['hours'] ?? '6');
        $competency = trim((string) ($spec['competency'] ?? '')) ?: '(ครูไม่ได้ระบุ ให้กำหนดให้เหมาะสมกับหน่วยนี้)';

        return <<<TXT
            ร่างแผนการจัดการเรียนรู้มุ่งเน้นสมรรถนะตามแบบฟอร์ม สอศ.

            หน่วยการเรียนรู้: {$unit}
            สมรรถนะที่ครูระบุ: {$competency}
            จำนวนชั่วโมง: {$hours} ชั่วโมง
            สัปดาห์ที่: {$spec['week']}
            รูปแบบการจัดการเรียนรู้: {$spec['style']}

            ข้อกำหนดของคำตอบ — สำคัญมาก ห้ามผิดรูปแบบ:
            1. ตอบเป็น NDJSON เท่านั้น หนึ่งหัวข้อต่อหนึ่งบรรทัด ห้ามครอบด้วย ``` ห้ามมีคำอธิบายนอก JSON
            2. บรรทัดแรกคือ {"meta":{"unit":"{$unit}","hours":"{$hours}"}}
            3. จากนั้นหนึ่งบรรทัดต่อหนึ่งหัวข้อ ในรูปแบบ {"head":"ชื่อหัวข้อ","body":"เนื้อหา"} ตามลำดับนี้
               1. สมรรถนะประจำหน่วย
               2. จุดประสงค์เชิงพฤติกรรม (เขียนเป็นข้อ 2.1–2.4 คั่นด้วย \\n)
               3. สาระการเรียนรู้ (เขียนเป็นข้อ 3.1–3.4 คั่นด้วย \\n)
               4. กิจกรรมการเรียนรู้ ({$hours} ชั่วโมง) — แยกขั้นนำ ขั้นสอน ขั้นปฏิบัติ ขั้นสรุป พร้อมเวลาแต่ละขั้นรวมกันได้ตามจำนวนชั่วโมง
